#pragma once

#include "../file_input.h"
#include <cstdio>
#include <dirent.h>
#include <string>
#include <utility>

// At most one untrusted sample. The caller keeps the opt-in session state.
class RejectedDownload {
public:
    static constexpr uint64_t limit = 192ULL * 1024 * 1024;

    explicit RejectedDownload(std::string path) : path_(std::move(path)) {}

    uint64_t size() const {
        FileInput input(path_.c_str());
        uint64_t bytes = 0;
        return input && input.measure(bytes) ? bytes : 0;
    }

    bool keep(const std::string& source) const {
        FileInput input(source.c_str());
        uint64_t bytes = 0;
        return input && input.measure(bytes) && bytes > 0 && bytes <= limit &&
               rename(source.c_str(), path_.c_str()) == 0;
    }

    bool clear() const {
        return unlink(path_.c_str()) == 0 || errno == ENOENT;
    }

private:
    std::string path_;
};

// Names of unpublished files generated by mkstemp. Published .pkg files
// and the opt-in diagnostic sample are outside this cleanup.
inline bool interruptedDownloadName(const std::string& name) {
    const auto marker = name.rfind(".part-");
    if (marker == std::string::npos || name.size() - marker != 12 || marker < 5) return false;
    size_t stemSize = 0;
    if (name.compare(marker - 4, 4, ".pkg") == 0) stemSize = marker - 4;
    else if (marker > 8 && name.compare(marker - 8, 8, ".xavatar") == 0) stemSize = marker - 8;
    if (!stemSize) return false;
    for (size_t i = 0; i < name.size(); ++i) {
        if (i == stemSize) i = marker + 6;
        const char c = name[i];
        const bool alnum = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9');
        if (!alnum && !(i < stemSize && (c == '-' || c == '_'))) return false;
    }
    return true;
}

inline size_t cleanupInterruptedDownloads(const std::string& directory) {
    DIR* listed = opendir(directory.c_str());
    if (!listed) return 0;
    size_t count = 0;
    while (auto* file = readdir(listed)) {
        const std::string name = file->d_name;
        if (interruptedDownloadName(name) && unlink((directory + "/" + name).c_str()) == 0) ++count;
    }
    closedir(listed);
    return count;
}
